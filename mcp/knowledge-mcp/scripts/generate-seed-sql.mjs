#!/usr/bin/env node
/**
 * Regenerates scripts/seed-clause-catalog.sql from the in-repo clause data.
 *
 * Sources (in-repo ONLY, per DESIGN.md workstream 2):
 *   1. backend/prisma/seeds/far/clauses.json  (52 FAR clauses)
 *   2. backend/prisma/seeds/far/dfars.json    (15 DFARS clauses)
 *   3. Two FAR clauses present only in CLAUSE_LIBRARY
 *      (backend/src/services/complianceGapAnalysis.ts): 52.225-5 and
 *      52.232-33, with plainLanguage mapped to summary.
 *
 * No clause text is generated from model memory. The `text` column is
 * filled with an explicit summary-level marker because the schema requires
 * a non-null value and full clause text has not been ingested.
 *
 * Usage: node scripts/generate-seed-sql.mjs
 * Output: scripts/seed-clause-catalog.sql (idempotent, ON CONFLICT DO NOTHING)
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..", "..");
const seedDir = path.join(repoRoot, "backend", "prisma", "seeds", "far");

const SUMMARY_LEVEL_TEXT = "[Summary-level entry, full clause text not yet ingested]";

/**
 * The two clauses that exist in CLAUSE_LIBRARY
 * (backend/src/services/complianceGapAnalysis.ts) but not in the JSON
 * catalog. plainLanguage is mapped to summary verbatim. Codes are
 * normalized to the catalog convention (no "FAR " prefix).
 */
const CLAUSE_LIBRARY_EXTRAS = [
  {
    code: "52.225-5",
    partNumber: "52",
    subpartNumber: "52.2",
    title: "Trade Agreements Act",
    summary:
      "Products you supply must be made in the U.S. or a country with a U.S. trade agreement (specific list). Excludes most non-WTO countries.",
    tags: ["TRADE_AGREEMENTS"],
  },
  {
    code: "52.232-33",
    partNumber: "52",
    subpartNumber: "52.2",
    title: "Payment by Electronic Funds Transfer - System for Award Management",
    summary:
      "You must accept payment via Electronic Funds Transfer (EFT). Banking info goes in your SAM.gov profile.",
    tags: ["PAYMENT"],
  },
];

function q(value) {
  if (value === null || value === undefined) return "NULL";
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function arr(values) {
  const list = values ?? [];
  if (list.length === 0) return "ARRAY[]::text[]";
  return "ARRAY[" + list.map((v) => q(v)).join(", ") + "]::text[]";
}

function num(value) {
  if (value === null || value === undefined) return "NULL";
  return String(Number(value));
}

function bool(value) {
  return value === true ? "true" : "false";
}

function seedId(source, code) {
  return `knowledge-mcp-seed-${source}-${code.replace(/[^0-9A-Za-z]/g, "-")}`;
}

function farRow(c) {
  return [
    q(seedId("far", c.code)),
    q(c.code),
    q(c.partNumber),
    q(c.subpartNumber ?? null),
    q(c.title),
    q(c.prescribedAt ?? null),
    arr(c.applicableContractTypes),
    arr(c.setAsideTriggers),
    arr(c.agencyTriggers),
    bool(c.flowDownRequired),
    num(c.flowDownThreshold),
    arr(c.prerequisiteClauseCodes),
    arr(c.prohibitedClauseCodes),
    bool(c.commercialItemException),
    bool(c.isBlocking),
    "NULL",
    "NULL",
    q(SUMMARY_LEVEL_TEXT),
    q(c.summary ?? null),
    arr(c.tags),
  ].join(", ");
}

function dfarsRow(c) {
  return [
    q(seedId("dfars", c.code)),
    q(c.code),
    q(c.partNumber),
    q(c.title),
    q(c.prescribedAt ?? null),
    arr(c.applicableContractTypes),
    arr(c.agencyTriggers),
    bool(c.flowDownRequired),
    num(c.flowDownThreshold),
    arr(c.prerequisiteClauseCodes),
    bool(c.isBlocking),
    "NULL",
    "NULL",
    q(SUMMARY_LEVEL_TEXT),
    q(c.summary ?? null),
    arr(c.tags),
  ].join(", ");
}

const farClauses = JSON.parse(readFileSync(path.join(seedDir, "clauses.json"), "utf8"));
const dfarsClauses = JSON.parse(readFileSync(path.join(seedDir, "dfars.json"), "utf8"));

const allFar = [...farClauses, ...CLAUSE_LIBRARY_EXTRAS];

const lines = [];
lines.push("-- =============================================================");
lines.push("-- knowledge-mcp v0.1.0 clause catalog seed");
lines.push("-- Generated by scripts/generate-seed-sql.mjs. Do not hand-edit;");
lines.push("-- regenerate instead.");
lines.push("--");
lines.push("-- Sources (in-repo only):");
lines.push("--   backend/prisma/seeds/far/clauses.json (" + farClauses.length + " FAR clauses)");
lines.push("--   backend/prisma/seeds/far/dfars.json (" + dfarsClauses.length + " DFARS clauses)");
lines.push("--   backend/src/services/complianceGapAnalysis.ts CLAUSE_LIBRARY");
lines.push("--     (2 FAR clauses not in the JSON catalog: 52.225-5, 52.232-33;");
lines.push("--      plainLanguage mapped to summary)");
lines.push("--");
lines.push("-- The text column carries an explicit summary-level marker because");
lines.push("-- full clause text has not been ingested and must not be generated");
lines.push("-- from model memory. Idempotent: ON CONFLICT DO NOTHING.");
lines.push("--");
lines.push("-- Apply (PowerShell):");
lines.push("--   Get-Content scripts/seed-clause-catalog.sql -Raw |");
lines.push("--     docker exec -i govcon_postgres psql -U govcon_user -d govcon_platform");
lines.push("-- =============================================================");
lines.push("");
lines.push("BEGIN;");
lines.push("");
lines.push("-- ---------- far_clauses (" + allFar.length + " rows) ----------");
for (const c of allFar) {
  lines.push("INSERT INTO far_clauses");
  lines.push(
    '  (id, code, "partNumber", "subpartNumber", title, "prescribedAt", "applicableContractTypes", "setAsideTriggers", "agencyTriggers", "flowDownRequired", "flowDownThreshold", "prerequisiteClauseCodes", "prohibitedClauseCodes", "commercialItemException", "isBlocking", "effectiveDate", "lastRevisedDate", text, summary, tags)'
  );
  lines.push("VALUES (" + farRow(c) + ")");
  lines.push("ON CONFLICT DO NOTHING;");
  lines.push("");
}
lines.push("-- ---------- dfars_clauses (" + dfarsClauses.length + " rows) ----------");
for (const c of dfarsClauses) {
  lines.push("INSERT INTO dfars_clauses");
  lines.push(
    '  (id, code, "partNumber", title, "prescribedAt", "applicableContractTypes", "agencyTriggers", "flowDownRequired", "flowDownThreshold", "prerequisiteClauseCodes", "isBlocking", "effectiveDate", "lastRevisedDate", text, summary, tags)'
  );
  lines.push("VALUES (" + dfarsRow(c) + ")");
  lines.push("ON CONFLICT DO NOTHING;");
  lines.push("");
}
lines.push("COMMIT;");
lines.push("");

const outPath = path.join(here, "seed-clause-catalog.sql");
writeFileSync(outPath, lines.join("\n"), "utf8");
process.stderr.write(
  `wrote ${outPath}: ${allFar.length} FAR rows, ${dfarsClauses.length} DFARS rows\n`
);
